"""Validate eight-language coverage and generate the browser dictionary."""
import html,json,re
from pathlib import Path
from html.parser import HTMLParser

ROOT=Path(__file__).resolve().parents[1]
CODES=['zh','zh-TW','en','fr','de','ru','ja','ko']
NAMES=['简体中文','繁體中文','English','Français','Deutsch','Русский','日本語','한국어']

def required_terms():
    terms={}
    class Labels(HTMLParser):
        def handle_starttag(self,tag,attrs):
            attrs=dict(attrs)
            for prefix in ['data-','data-placeholder-','data-title-']:
                if prefix+'en' in attrs:terms[attrs[prefix+'en']]=attrs[prefix+'zh']
    Labels().feed((ROOT/'web/index.html').read_text('utf-8'))
    source='\n'.join((ROOT/'web'/name).read_text('utf-8') for name in ['app.js','forms.js','timezone-picker.js','printer-manager.js','online-update.js'])
    for zh,en in re.findall(r"(?:text\(|t\(|\[)'([^']*)','([^']*)'",source):
        if re.search('[\u4e00-\u9fff]',zh):terms[en]=zh
    return terms

def generate():
    words=json.loads((ROOT/'resources/locales.json').read_text('utf-8'))
    for key in required_terms():
        assert key in words,f'Missing translation: {key}'
    for key,row in words.items():
        assert len(row)==8 and all(isinstance(x,str) and x.strip() for x in row),f'Incomplete translation: {key}'
        assert row[2]==key,f'English key mismatch: {key}'
    value='// Generated by scripts/generate_locales.py.\nwindow.MatrixLocales='+json.dumps({'codes':CODES,'names':NAMES,'words':words},ensure_ascii=False,separators=(',',':'))+';\n'
    target=ROOT/'web/locales.js'
    if not target.exists() or target.read_text('utf-8')!=value:target.write_text(value,encoding='utf-8')
    print(f'Validated {len(words)} entries in all eight languages.')

if __name__=='__main__':generate()
